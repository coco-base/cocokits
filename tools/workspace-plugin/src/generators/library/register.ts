import { readJson, updateJson, writeJson, type Tree } from '@nx/devkit';
import { sortExports, sortKeys, type ExportValue } from './package-json';
import { entryPoint, type EntryPoint, type PackageSpec } from './spec';

/** Registers an entry point in the root tsconfig `paths` (relative, no baseUrl). */
export function addTsconfigPath(tree: Tree, entry: EntryPoint): void {
  updateJson<{ compilerOptions?: { paths?: Record<string, string[]> } }>(tree, 'tsconfig.base.json', (json) => {
    const options = (json.compilerOptions ??= {});
    const paths = (options.paths ??= {});
    if (paths[entry.specifier] === undefined) {
      paths[entry.specifier] = [entry.source];
      options.paths = sortKeys(paths);
    }
    return json;
  });
}

/** Adds an `exports` key to the package.json of `spec` if it is missing; never rewrites an existing key. Not for ng-packagr packages. */
export function addPackageExport(tree: Tree, spec: PackageSpec, entry: EntryPoint): void {
  // ng-packagr generates the exports of its output package.json from the entry points (see initialExports).
  if (spec.builder === 'ng-packagr') return;
  updateJson<{ exports?: Record<string, ExportValue> }>(tree, `${spec.root}/package.json`, (json) => {
    const exportsMap = (json.exports ??= {});
    if (exportsMap[entry.key] === undefined) {
      exportsMap[entry.key] = { types: entry.types, default: entry.default };
      json.exports = sortExports(exportsMap);
    }
    return json;
  });
}

const SIZE_FILE = 'size-limit.config.mjs';
const SIZE_HEADER = [
  '// Generated by `nx g @cocokits/workspace:library`. Do not edit by hand: budgets are raised in the PR that justifies it.',
  '// Every entry has a budget (brotli bytes), so `pnpm size` fails on a regression. An entry is bundled with esbuild,',
  '// so its budget covers the implementation it reaches, not only its re-exports; packages (`@cocokits/*`, peers) stay',
  '// external. A stylesheet is bundled too, so it is measured minified. A budget is the size when it was set plus 10%',
  '// (at least 50 B), rounded up to 10 B (100 B from 10 kB). The generator gives a new entry 2 kB.',
  '// `tsconfigRaw`: without it esbuild maps `@cocokits/*` to the sources through the `paths` of tsconfig.base.json.',
  "const external = (config) => ({ ...config, packages: 'external', tsconfigRaw: '{}' });",
].join('\n');
const SIZE_FOOTER = 'export default entries.map((entry) => ({ ...entry, modifyEsbuildConfig: external }));';

/** The budget of a new entry. Every entry has one, so `pnpm size` fails on a regression; raise it in the PR that grows the entry. */
const DEFAULT_LIMIT = '2 kB';

export interface SizeEntry {
  readonly name: string;
  readonly path: string;
}

function sizeLine({ name, path }: SizeEntry): string {
  return `  { name: '${name}', path: '${path}', limit: '${DEFAULT_LIMIT}' },`;
}

function hasEntry(content: string, name: string): boolean {
  return content.includes(`'${name}'`) || content.includes(`"${name}"`);
}

/**
 * Creates size-limit.config.mjs when missing and appends the entries that are not listed yet. Existing
 * entries are never rewritten, so custom `limit` or `brotli` options survive.
 */
export function addSizeEntries(tree: Tree, additions: readonly SizeEntry[]): void {
  const current = tree.read(SIZE_FILE, 'utf-8');
  let content = current ?? `${SIZE_HEADER}\n\nconst entries = [];\n\n${SIZE_FOOTER}\n`;
  const fresh = [...new Map(additions.map((entry) => [entry.name, entry])).values()]
    .filter(({ name }) => !hasEntry(content, name))
    .sort((a, b) => a.name.localeCompare(b.name));
  const end = content.lastIndexOf('];');
  if (fresh.length > 0 && end !== -1) {
    const before = content.slice(0, end).trimEnd();
    const separator = /[[,]$/.test(before) ? '' : ',';
    content = `${before}${separator}\n${fresh.map(sizeLine).join('\n')}\n${content.slice(end)}`;
  }
  if (current !== content) tree.write(SIZE_FILE, content);
}

export function sizeEntriesOf(entries: readonly EntryPoint[]): SizeEntry[] {
  return entries.map((entry) => ({ name: entry.specifier, path: entry.sizePath }));
}

/** Size entries of a theme core's CSS asset exports (the components glob is measured per file later). */
export function cssSizeEntries(spec: PackageSpec): SizeEntry[] {
  return ['styles.css', 'tokens.css'].map((file) => ({
    name: `${spec.packageName}/${file}`,
    path: `${spec.root}/dist/${file}`,
  }));
}

/** Adds the package to explicit `fixed` groups of the Changesets config; a glob group already covers it. */
export function addToChangesetGroup(tree: Tree, packageName: string): void {
  const file = '.changeset/config.json';
  if (!tree.exists(file)) return;
  const config = readJson<{ fixed?: string[][] }>(tree, file);
  const groups = config.fixed ?? [];
  const explicit = groups.filter((group) => group.length > 0 && !group.some((entry) => entry.includes('*')));
  if (explicit.length === 0 || groups.some((group) => group.includes(packageName))) return;
  const [first] = explicit;
  if (first) first.push(packageName);
  writeJson(tree, file, config);
}

export function rootEntryOf(spec: PackageSpec): EntryPoint[] {
  return spec.rootEntry ? [entryPoint(spec, undefined)] : [];
}
