import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it, vi } from 'vitest';
import executor from './executor';
import { emitTokens, modeCollectionsOf } from './emit';
import { emitModes } from './modes';
import type { Collection, TokenFile } from './types';

const collection = (name: string, modes: string[], defaultMode = modes[0] ?? ''): Collection => ({
  name,
  tier: 2,
  defaultMode,
  modes,
  tokens: [],
});

const file = (...collections: Collection[]): TokenFile => ({ $meta: { globalPrefix: 'cck' }, collections });

/** The `modeCollections` array of a generated file: one JSON object per line between the brackets. */
function modeCollectionsIn(out: string): { name: string; attrName: string; modes: { name: string }[] }[] {
  const start = out.indexOf('export const modeCollections: readonly ModeCollection[] = [');
  const body = out.slice(out.indexOf('\n', start) + 1, out.lastIndexOf('\n];'));
  return JSON.parse(`[${body.replace(/,$/, '')}]`) as ReturnType<typeof modeCollectionsIn>;
}

describe('emitModes', () => {
  it('emits the list, the union and the default for a multi-mode collection, in JSON order', () => {
    const out = emitModes(file(collection('Theme / Active Color', ['brand', 'danger', 'info'], 'brand')));
    expect(out).toContain('// Generated by @cocokits/workspace:tokens. Do not edit.');
    expect(out).toContain('export const themeActiveColorModes = ["brand", "danger", "info"] as const;');
    expect(out).toContain('export type ThemeActiveColorMode = (typeof themeActiveColorModes)[number];');
    expect(out).toContain('export const themeActiveColorDefaultMode: ThemeActiveColorMode = "brand";');
  });

  it('derives the names from the full collection name, for any collection', () => {
    const out = emitModes(
      file(collection('Button / Size', ['sm', 'md'], 'md'), collection('Theme / Color', ['Light', 'Dark'])),
    );
    expect(out).toContain('export const buttonSizeModes = ["sm", "md"] as const;');
    expect(out).toContain('export type ButtonSizeMode');
    expect(out).toContain('export const buttonSizeDefaultMode: ButtonSizeMode = "md";');
    expect(out).toContain('export const themeColorModes = ["Light", "Dark"] as const;');
  });

  it('emits no mode list for a single-mode collection', () => {
    const out = emitModes(file(collection('Core / Size', ['Default'])));
    expect(out).not.toContain('coreSizeModes');
  });

  it('fails when the default mode is not in the modes', () => {
    expect(() => emitModes(file(collection('Button / Size', ['sm', 'md'], 'xl')))).toThrow(
      /Button \/ Size: defaultMode "xl"/,
    );
  });

  it('fails when two collections make the same names', () => {
    expect(() => emitModes(file(collection('A / B', ['x', 'y']), collection('A B', ['x', 'y'])))).toThrow(/aBModes/);
  });

  it('serializes hostile mode names as string literals', () => {
    const hostile = ['a"b', 'c\\d', 'e\nf', 'g*/h', '"; process.exit(1); //'];
    const out = emitModes(file(collection('Button / Size', hostile, hostile[0])));
    const list = hostile.map((mode) => JSON.stringify(mode)).join(', ');
    expect(out).toContain(`export const buttonSizeModes = [${list}] as const;`);
    expect(out).toContain(`= ${JSON.stringify(hostile[0])};`);
    // every line after the header is a plain export line: nothing broke out of a literal
    const plain = (line: string): boolean => /^(export |import type |\/\/ | {2}\{.*\},$|\];$)/.test(line);
    expect(out.split('\n').filter((line) => line && !plain(line))).toEqual([]);
    expect(modeCollectionsIn(out)[0]?.modes.map((mode) => mode.name)).toEqual(hostile);
  });

  it('fails when a collection name makes no valid identifier', () => {
    expect(() => emitModes(file(collection('1 / Size', ['x', 'y'])))).toThrow(/valid identifier/);
    expect(() => emitModes(file(collection('/ ;', ['x', 'y'])))).toThrow(/valid identifier/);
  });

  it('turns a name that would inject a statement into plain identifier characters', () => {
    const out = emitModes(file(collection('Evil = 1; alert(1) / Size', ['x', 'y'])));
    expect(out).toContain('export const evil1Alert1SizeModes = [');
    // the name appears only as a JSON string in the modes index
    expect(out.split('\n').filter((line) => line.includes('alert(1)'))).toEqual([
      `  ${JSON.stringify(modeCollectionsIn(out)[0])},`,
    ]);
    expect(modeCollectionsIn(out)[0]?.name).toBe('Evil = 1; alert(1) / Size');
  });

  it('rejects paths that leave the workspace', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'modes-'));
    try {
      writeFileSync(join(dir, 'a.json'), JSON.stringify(file(collection('Button / Size', ['sm', 'md'], 'md'))));
      const outside = join(dir, '..', 'outside.ts');
      for (const options of [
        { input: 'a.json', output: 'o.css', modesOutput: '../outside.ts' },
        { input: 'a.json', output: 'o.css', modesOutput: outside },
        { input: 'a.json', output: '../o.css' },
        { input: '../a.json', output: 'o.css' },
      ]) {
        const result = await executor(options, { root: dir } as never);
        expect(result.success).toBe(false);
      }
      expect(existsSync(outside)).toBe(false);
      expect(existsSync(join(dir, 'o.css'))).toBe(false);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it('puts no input-derived text in the header, even for a path with line separators', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'modes-'));
    try {
      const name = 'a\u2028export const evil = 1;\u2029.json';
      try {
        writeFileSync(join(dir, name), JSON.stringify(file(collection('Button / Size', ['sm', 'md'], 'md'))));
      } catch {
        return; // the OS refuses such a file name; emitModes' header is fixed anyway
      }
      const result = await executor({ input: name, output: 'o.css', modesOutput: 'm.ts' }, { root: dir } as never);
      expect(result.success).toBe(true);
      const out = readFileSync(join(dir, 'm.ts'), 'utf8');
      expect(out.split('\n')[0]).toBe('// Generated by @cocokits/workspace:tokens. Do not edit.');
      expect(out).not.toContain('evil');
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it('rejects an output that goes through a link to a directory outside the workspace', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'modes-'));
    const outside = mkdtempSync(join(tmpdir(), 'modes-outside-'));
    try {
      writeFileSync(join(dir, 'a.json'), JSON.stringify(file(collection('Button / Size', ['sm', 'md'], 'md'))));
      try {
        symlinkSync(outside, join(dir, 'link'), 'junction');
      } catch {
        return; // the OS refuses to create the link
      }
      for (const options of [
        { input: 'a.json', output: 'link/o.css' },
        { input: 'a.json', output: 'o.css', modesOutput: 'link/new/m.ts' },
      ]) {
        expect((await executor(options, { root: dir } as never)).success).toBe(false);
      }
      expect(readdirSync(outside)).toEqual([]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
      rmSync(outside, { recursive: true, force: true });
    }
  });

  it('rejects an output that is a link to a file outside the workspace', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'modes-'));
    const outside = mkdtempSync(join(tmpdir(), 'modes-outside-'));
    try {
      writeFileSync(join(dir, 'a.json'), JSON.stringify(file(collection('Button / Size', ['sm', 'md'], 'md'))));
      const target = join(outside, 'target.ts');
      writeFileSync(target, 'untouched');
      try {
        symlinkSync(target, join(dir, 'm.ts'), 'file');
      } catch {
        return; // the OS refuses to create the link (file links need a privilege on Windows)
      }
      const result = await executor({ input: 'a.json', output: 'o.css', modesOutput: 'm.ts' }, { root: dir } as never);
      expect(result.success).toBe(false);
      expect(readFileSync(target, 'utf8')).toBe('untouched');
    } finally {
      rmSync(dir, { recursive: true, force: true });
      rmSync(outside, { recursive: true, force: true });
    }
  });

  it('is written by the executor only when modesOutput is set', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'modes-'));
    try {
      writeFileSync(join(dir, 'a.json'), JSON.stringify(file(collection('Button / Size', ['sm', 'md'], 'md'))));
      await executor({ input: 'a.json', output: 'out.css', modesOutput: 'gen/modes.ts' }, { root: dir } as never);
      expect(readFileSync(join(dir, 'gen/modes.ts'), 'utf8')).toContain('buttonSizeModes');
      const failed = await executor({ input: 'a.json', output: 'o.css', modesOutput: 'x.ts' }, {
        root: join(dir, 'missing'),
      } as never);
      expect(failed.success).toBe(false);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

describe('modeCollections, the modes index', () => {
  const tiered = (name: string, tier: Collection['tier'], modes: string[], defaultMode = modes[0]): Collection => ({
    ...collection(name, modes, defaultMode),
    tier,
  });
  const withTokens = (tokens: TokenFile): TokenFile => ({
    ...tokens,
    collections: tokens.collections.map((item) => ({
      ...item,
      tokens: [{ name: item.name, type: 'string', valuesByMode: Object.fromEntries(item.modes.map((m) => [m, 'x'])) }],
    })),
  });

  it('gives a theme with another prefix exactly its attributes and mode values, as the selectors use them', () => {
    const tokens = withTokens({
      $meta: { globalPrefix: 'acme' },
      collections: [
        tiered('Core / Size', 1, ['Default']),
        tiered('Mood', 2, ['Day', 'Night Sky']),
        tiered('Theme / Density', 2, ['Normal']),
        tiered('Card / Size', 3, ['Small', 'Large'], 'Large'),
        tiered('Card / Structure', 3, ['Default']),
      ],
    });
    expect(modeCollectionsOf(tokens)).toEqual([
      {
        name: 'Mood',
        attrName: 'acme-mood',
        modes: [
          { name: 'Day', value: 'day' },
          { name: 'Night Sky', value: 'night-sky' },
        ],
        defaultMode: 'Day',
      },
      {
        name: 'Theme / Density',
        attrName: 'acme-density',
        modes: [{ name: 'Normal', value: 'normal' }],
        defaultMode: 'Normal',
      },
      {
        name: 'Card / Size',
        attrName: 'size',
        componentName: 'card',
        modes: [
          { name: 'Small', value: 'small' },
          { name: 'Large', value: 'large' },
        ],
        defaultMode: 'Large',
      },
    ]);
    const css = emitTokens(tokens, 'css');
    expect(css).toContain('[data-acme-mood="night-sky"]');
    expect(css).toContain('.cck-card[data-size="small"]');
    expect(modeCollectionsIn(emitModes(tokens))).toEqual(modeCollectionsOf(tokens));
  });

  it('is typed with ModeCollection from @cocokits/shared and holds no docs field', () => {
    const out = emitModes(file(collection('Theme / Color', ['Light', 'Dark'])));
    expect(out.split('\n')[1]).toBe("import type { ModeCollection } from '@cocokits/shared';");
    expect(modeCollectionsIn(out)).toEqual([
      {
        name: 'Theme / Color',
        attrName: 'cck-color-mode',
        modes: [
          { name: 'Light', value: 'light' },
          { name: 'Dark', value: 'dark' },
        ],
        defaultMode: 'Light',
      },
    ]);
  });

  it.each(['page', 'label', 'colorScheme'])('fails the target on a collection with "%s", naming it', async (field) => {
    const bad = { ...collection('Theme / Color', ['Light', 'Dark']), [field]: field === 'page' ? true : 'x' };
    expect(() => emitTokens(file(bad), 'css')).toThrow(`Theme / Color: unknown collection field "${field}"`);
    const dir = mkdtempSync(join(tmpdir(), 'modes-'));
    const error = vi.spyOn(console, 'error').mockImplementation(() => undefined);
    try {
      writeFileSync(join(dir, 'a.json'), JSON.stringify(file(bad)));
      const result = await executor({ input: 'a.json', output: 'o.css', modesOutput: 'm.ts' }, { root: dir } as never);
      expect(result.success).toBe(false);
      expect(String(error.mock.calls[0]?.[0])).toContain(`unknown collection field "${field}"`);
      expect(existsSync(join(dir, 'm.ts'))).toBe(false);
      expect(existsSync(join(dir, 'o.css'))).toBe(false);
    } finally {
      error.mockRestore();
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it('fails when two collections of one scope make the same attribute', () => {
    expect(() => emitModes(file(collection('A / Mood', ['x', 'y']), collection('B / Mood', ['x', 'y'])))).toThrow(
      'B / Mood: the mode attribute cck-mood is also made by A / Mood',
    );
    const size = (name: string): Collection => tiered(name, 3, ['sm', 'md']);
    expect(() => modeCollectionsOf(file(size('Button / Size'), size('Button / Size')))).toThrow(/attribute size/);
    const shared = modeCollectionsOf(file(size('Button / Size'), size('Input / Size')));
    expect(shared.map((item) => [item.componentName, item.attrName])).toEqual([
      ['button', 'size'],
      ['input', 'size'],
    ]);
  });
});
