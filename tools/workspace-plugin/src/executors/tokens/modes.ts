import { checkDefaultMode, modeCollectionsOf } from './emit';
import type { Collection, TokenFile } from './types';

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const words = (text: string): string[] => text.split(/[^A-Za-z0-9]+/).filter(Boolean);
const pascal = (text: string): string =>
  words(text)
    .map((word) => `${word.charAt(0).toUpperCase()}${word.slice(1)}`)
    .join('');

/** `Theme / Active Color` is `themeActiveColor`: the camelCase of the full collection name. */
const stemOf = (collection: Collection): string => {
  const name = pascal(collection.name);
  return `${name.charAt(0).toLowerCase()}${name.slice(1)}`;
};

/**
 * Turns every collection with more than one mode into three exports: the mode list (a readonly tuple in
 * JSON order), its union type and the default mode. A single-mode collection emits none of them. Last comes the
 * modes index `modeCollections` (`modeCollectionsOf`), typed with `ModeCollection` from `@cocokits/shared`.
 * Throws when a collection's `defaultMode` is not in its `modes`, and on every error of `modeCollectionsOf`.
 */
export function emitModes(file: TokenFile): string {
  const index = modeCollectionsOf(file);
  const lines = [
    '// Generated by @cocokits/workspace:tokens. Do not edit.',
    "import type { ModeCollection } from '@cocokits/shared';",
  ];
  const seen = new Set<string>();
  for (const collection of file.collections) {
    checkDefaultMode(collection);
    if (collection.modes.length < 2) continue;
    const stem = stemOf(collection);
    if (!IDENTIFIER.test(stem)) {
      throw new Error(`${collection.name}: the name does not make a valid identifier (${JSON.stringify(stem)})`);
    }
    if (seen.has(stem))
      throw new Error(`${collection.name}: the export name ${stem}Modes is also made by another collection`);
    seen.add(stem);
    const type = `${pascal(collection.name)}Mode`;
    const list = collection.modes.map((mode) => JSON.stringify(mode)).join(', ');
    lines.push(
      '',
      `export const ${stem}Modes = [${list}] as const;`,
      `export type ${type} = (typeof ${stem}Modes)[number];`,
      `export const ${stem}DefaultMode: ${type} = ${JSON.stringify(collection.defaultMode)};`,
    );
  }
  const entries = index.map((collection) => `  ${JSON.stringify(collection)},`);
  lines.push('', 'export const modeCollections: readonly ModeCollection[] = [', ...entries, '];');
  return `${lines.join('\n')}\n`;
}
