import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { emitTokens, mergeTokenFiles } from './emit';
import executor from './executor';
import type { Collection, Token, TokenFile } from './types';

const core: Collection = {
  name: 'Core / Size',
  tier: 1,
  defaultMode: 'Default',
  modes: ['Default'],
  tokens: [
    { name: 'size-8', type: 'number', unit: 'px', valuesByMode: { Default: 8 } },
    { name: 'line-height/tight', type: 'number', unit: 'unitless', valuesByMode: { Default: 1.2 } },
    { name: 'secret', type: 'number', unit: 'px', valuesByMode: { Default: 1 } },
  ],
};

const color: Collection = {
  name: 'Theme / Color',
  tier: 2,
  defaultMode: 'Light',
  modes: ['Light', 'Dark'],
  tokens: [{ name: 'brand/color', type: 'color', valuesByMode: { Light: '#fff', Dark: '#000' } }],
};

const spacing: Collection = {
  name: 'Theme / Spacing',
  tier: 2,
  defaultMode: 'Normal',
  modes: ['Normal'],
  tokens: [
    { name: 'spacing-1', type: 'number', unit: 'px', valuesByMode: { Normal: '{Core / Size#size-8}' } },
    { name: 'spacing-0', type: 'number', unit: 'px', valuesByMode: { Normal: 0 } },
  ],
};

const active: Collection = {
  name: 'Theme / Active Color',
  tier: 2,
  defaultMode: 'brand',
  modes: ['brand', 'danger'],
  tokens: [
    {
      name: 'color',
      type: 'color',
      valuesByMode: { brand: '{Theme / Color#brand/color}', danger: '{Theme / Color#brand/color}' },
    },
  ],
};

const brand: Collection = {
  name: 'Theme / Brand',
  tier: 2,
  prefix: 'ramp',
  defaultMode: 'Dahlia',
  modes: ['Dahlia'],
  tokens: [{ name: 'brand/base', type: 'color', valuesByMode: { Dahlia: '#7c3aed' } }],
};

const file = (...collections: Collection[]): TokenFile => ({ $meta: { globalPrefix: 'cck' }, collections });
const clone = <T>(value: T): T => structuredClone(value);
const first = (collection: Collection, valuesByMode: Token['valuesByMode']): Collection => {
  const copy = clone(collection);
  copy.tokens = copy.tokens.map((token, index) => (index === 0 ? { ...token, valuesByMode } : token));
  return copy;
};
const all = file(core, brand, color, active, spacing);

describe('emitTokens', () => {
  it('writes the header and wraps everything in the cocokits layer', () => {
    const css = emitTokens(all, 'css');
    const header = '/* Generated by @cocokits/workspace:tokens. Do not edit. */\n@layer cocokits {';
    expect(css.startsWith(header)).toBe(true);
    expect(css.trimEnd().endsWith('}')).toBe(true);
  });

  it('names variables with the prefix, the collection prefix and no marker', () => {
    const css = emitTokens(all, 'css');
    expect(css).toContain('--cck-size-8: 8px;');
    expect(css).toContain('--cck-line-height-tight: 1.2;');
    expect(css).toContain('--cck-secret: 1px;');
    expect(css).toContain('--cck-ramp-brand-base: #7c3aed;');
    expect(css).toContain('--cck-brand-color: #fff;');
  });

  it('emits aliases as var() and zero with its unit', () => {
    const css = emitTokens(all, 'css');
    expect(css).toContain('--cck-spacing-1: var(--cck-size-8);');
    expect(css).toContain('--cck-spacing-0: 0px;');
  });

  it('emits tier 1 at :root and tier 2 modes on attribute selectors in mode order', () => {
    const css = emitTokens(all, 'css');
    expect(css).toContain('  :root {\n    --cck-size-8');
    expect(css).toContain(':root, [data-cck-color-mode="light"] {');
    expect(css.indexOf('[data-cck-color-mode="light"]')).toBeLessThan(css.indexOf('[data-cck-color-mode="dark"]'));
    expect(css).toContain('  [data-cck-color-mode="dark"] {');
    expect(css).toContain(':root, [data-cck-brand="dahlia"] {');
    expect(css).toContain(':root, [data-cck-spacing="normal"] {');
  });

  it('gives Active Color one block per mode and no :root', () => {
    const css = emitTokens(all, 'css');
    expect(css).toContain('  [data-cck-color="brand"] {');
    expect(css).toContain('  [data-cck-color="danger"] {');
    expect(css).not.toContain(':root, [data-cck-color=');
  });

  it('adds a $ alias for every token, and only in scss', () => {
    const scss = emitTokens(all, 'scss');
    expect(scss).toContain('$cck-size-8: var(--cck-size-8);');
    expect(scss).toContain('$cck-ramp-brand-base: var(--cck-ramp-brand-base);');
    expect(scss).not.toContain('$--');
    expect(emitTokens(all, 'css')).not.toContain('$cck-');
  });

  it('puts the scss rules in a tokens mixin and none at top level', () => {
    const scss = emitTokens(all, 'scss');
    const [top, mixin] = scss.split('@mixin tokens {');
    expect(top).toContain('// Generated by @cocokits/workspace:tokens. Do not edit.');
    expect(top).not.toContain('{');
    expect(mixin).toContain('  @layer cocokits {');
    expect(mixin).toContain('    :root, [data-cck-color-mode="light"] {');
    expect(scss.trimEnd().endsWith('}')).toBe(true);
  });
});

describe('build errors', () => {
  it('rejects an alias to a missing token', () => {
    const bad = first(spacing, { Normal: '{Core / Size#size-9}' });
    expect(() => emitTokens(file(core, bad), 'css')).toThrow(/Theme \/ Spacing: spacing-1.*does not exist/);
  });

  it('rejects an alias to a missing collection', () => {
    const bad = first(spacing, { Normal: '{Nope#size-8}' });
    expect(() => emitTokens(file(core, bad), 'css')).toThrow(/spacing-1.*does not exist/);
  });

  it('rejects values that do not match the modes', () => {
    const bad = first(color, { Light: '#fff' });
    expect(() => emitTokens(file(bad), 'css')).toThrow(/Theme \/ Color: brand\/color.*modes/);
  });

  it('rejects two tokens with the same variable name', () => {
    const bad = clone(core);
    bad.tokens.push({ name: 'size/8', type: 'number', unit: 'px', valuesByMode: { Default: 8 } });
    expect(() => emitTokens(file(bad), 'css')).toThrow(/Core \/ Size: size\/8.*--cck-size-8/);
  });

  it('rejects a number without a known unit', () => {
    const unit = (value: string | undefined): Collection => ({
      ...core,
      tokens: [{ name: 'size-8', type: 'number', unit: value, valuesByMode: { Default: 8 } }],
    });
    expect(() => emitTokens(file(unit(undefined)), 'css')).toThrow('Core / Size: size-8');
    expect(() => emitTokens(file(unit('pt')), 'css')).toThrow(/size-8.*"pt"/);
  });

  it('rejects a :root token that aliases a multi-mode collection', () => {
    const bad = first(spacing, { Normal: '{Theme / Color#brand/color}' });
    expect(() => emitTokens(file(color, bad), 'css')).toThrow(/Theme \/ Spacing: spacing-1.*multi-mode/);
  });

  it('lets Active Color alias a multi-mode collection', () => {
    expect(() => emitTokens(file(color, active), 'css')).not.toThrow();
  });
});

describe('tokens executor', () => {
  let dir = '';
  afterEach(() => {
    rmSync(dir, { recursive: true, force: true });
  });

  const run = async (tokens: TokenFile): Promise<boolean> => {
    dir = mkdtempSync(join(tmpdir(), 'tokens-'));
    writeFileSync(join(dir, 'in.json'), JSON.stringify(tokens));
    const result = await executor({ input: 'in.json', output: 'out/tokens.css' }, { root: dir } as never);
    return result.success;
  };

  it('writes the output file', async () => {
    expect(await run(file(core))).toBe(true);
    expect(readFileSync(join(dir, 'out/tokens.css'), 'utf8')).toContain('--cck-size-8: 8px;');
  });

  it('fails on a broken alias', async () => {
    const bad = first(spacing, { Normal: '{Core / Size#missing}' });
    expect(await run(file(core, bad))).toBe(false);
  });
});

const size3: Collection = {
  name: 'Button / Size',
  tier: 3,
  prefix: 'button',
  defaultMode: 'md',
  modes: ['sm', 'md'],
  tokens: [
    {
      name: 'height',
      type: 'number',
      unit: 'px',
      valuesByMode: { sm: '{Core / Size#size-8}', md: '{Core / Size#size-8}' },
    },
  ],
};

const structure3: Collection = {
  name: 'Button / Structure',
  tier: 3,
  prefix: 'button',
  defaultMode: 'Default',
  modes: ['Default'],
  tokens: [
    { name: 'bg', type: 'color', valuesByMode: { Default: '{Theme / Active Color#color}' } },
    { name: 'radius', type: 'number', unit: 'px', valuesByMode: { Default: 4 } },
  ],
};

describe('tier 3 component tokens', () => {
  const tier3 = file(core, color, active, size3, structure3);

  it('emits Size modes on the component class and the default mode also bare', () => {
    const css = emitTokens(tier3, 'css');
    expect(css).toContain('  .cck-button[data-size="sm"] {\n    --cck-button-height: var(--cck-size-8);');
    expect(css).toContain('  .cck-button, .cck-button[data-size="md"] {');
  });

  it('emits Structure on the component class and aliases Active Color', () => {
    const css = emitTokens(tier3, 'css');
    expect(css).toContain('  .cck-button {\n    --cck-button-bg: var(--cck-color);');
    expect(css).toContain('--cck-button-radius: 4px;');
  });

  it('emits a collection with alsoFor for the other blocks too, with the same variables', () => {
    const shared = file(
      core,
      color,
      active,
      { ...size3, alsoFor: ['button-bar'] },
      { ...structure3, alsoFor: ['button-bar'] },
    );
    const css = emitTokens(shared, 'css');
    expect(css).toContain('  .cck-button[data-size="sm"], .cck-button-bar[data-size="sm"] {');
    expect(css).toContain(
      '  .cck-button, .cck-button[data-size="md"], .cck-button-bar, .cck-button-bar[data-size="md"] {',
    );
    expect(css).toContain('  .cck-button, .cck-button-bar {\n    --cck-button-bg: var(--cck-color);');
  });

  it('refuses an alsoFor entry that is not a block slug', () => {
    const bad = file(core, color, active, { ...structure3, alsoFor: ['Button Bar{'] });
    expect(() => emitTokens(bad, 'css')).toThrow(/alsoFor.*"Button Bar\{".*block slug/);
  });

  it('never emits a tier 3 token at :root', () => {
    const css = emitTokens(tier3, 'css');
    const blocks = css.split('  }').filter((block) => block.includes(':root'));
    expect(blocks.length).toBeGreaterThan(0);
    expect(blocks.join('')).not.toContain('--cck-button');
  });
});

describe('mergeTokenFiles', () => {
  it('merges collections so aliases cross files', () => {
    const merged = mergeTokenFiles([file(core, color, active), file(size3, structure3)]);
    expect(merged.collections).toHaveLength(5);
    expect(() => emitTokens(merged, 'css')).not.toThrow();
  });

  it('rejects a globalPrefix mismatch', () => {
    const other: TokenFile = { $meta: { globalPrefix: 'x' }, collections: [] };
    expect(() => mergeTokenFiles([file(core), other], ['a.json', 'b.json'])).toThrow(/b\.json.*globalPrefix/);
  });

  it('is used by the executor for several input files', async () => {
    const dir2 = mkdtempSync(join(tmpdir(), 'tokens-'));
    try {
      writeFileSync(join(dir2, 'a.json'), JSON.stringify(file(core, color, active)));
      writeFileSync(join(dir2, 'b.json'), JSON.stringify(file(size3, structure3)));
      const result = await executor({ input: ['a.json', 'b.json'], output: 'out.css' }, { root: dir2 } as never);
      expect(result.success).toBe(true);
      expect(readFileSync(join(dir2, 'out.css'), 'utf8')).toContain('--cck-button-bg');
    } finally {
      rmSync(dir2, { recursive: true, force: true });
    }
  });
});
